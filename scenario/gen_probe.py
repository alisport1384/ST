"""
سازندهٔ سناریوی عددی کنترل‌شده برای موتور GoldPin (سند GoldPin_strategy_final5_FA).

داده: کندل‌های M1 برای دوشنبه ۲۰۲۶-۱۰-۱۹ از ۰۲:۰۰ تا ۱۵:۳۰ UTC.
تایم‌فریم‌ها: مود ۱ → ساختار H1، میانی M15، تریگر۱ M5، تریگر۲ M1.

طرح سناریو (همهٔ اعداد دستی و عمداً ساده‌اند):
  ۰۲:۰۰ نزولی 2010.00→2005.00
  ۰۳:۰۰ صعودی 2005.00→2007.50   (low=1999.00 ⇒ کندل مهم پایین‌ترین‌ها)
  ۰۴:۰۰ صعودی 2007.50→2009.50   (کلوز بالای high کندل مهم ⇒ Ready BU / pinBU=1999.00)
  ۰۵:۰۰ نزولی 2009.50→2007.00   (high=2010.20 ⇒ کندل مهم بالاترین‌ها)
  ۰۶:۰۰ نزولی 2007.00→2004.00   (کلوز زیر low کندل مهم ⇒ Ready BE / pinBE=2010.20 ⇒ tempbox [1999.00 , 2010.20])
  ۰۷:۰۰ صعودی 2004.00→2012.10   (کلوز بالای سقف tempbox ⇒ روند صعودی)
  ۰۸:۰۰ صعودی 2012.10→2015.30   (پروفایل حجم کنترل‌شده ⇒ ناحیهٔ ساختار Z1 = [2012.20 , 2013.20])
  ۰۹:۰۰ صعودی 2015.30→2019.00
  ۱۰:۰۰ نزولی 2019.00→2017.00   (high=2022.00 ⇒ کندل مهم بالاترین‌ها)
  ۱۱:۰۰ نزولی 2017.00→2015.00   (کلوز زیر low کندل مهم ⇒ Ready BE ⇒ pinBE=2022.00 ⇒ HH=2022.00 ، HL=1999.00)
  ۱۲:۰۰ نزولی 2015.00→2013.60
  ۱۳:۰۰ صعودی 2013.60→2013.90   (برخورد با Z1 در ۱۳:۲۲ با low=2012.00 ⇒ تأیید میانی در کلوز M15 = ۱۳:۳۰ با کف 2012.00)
  ۱۳:۵۰ کندل ولوم کم روی M5 (حجم ۴۰۰ < ۵۰۰) ⇒ LV = [2012.60 , 2013.15]
  ۱۴:۰۰ کلوز M5 = 2013.40 > سقف LV ⇒ تأیید ناحیهٔ ولوم کم
  ۱۴:۰۶ بازگشت قیمت به باکس LV
  ۱۴:۱۱ کندل ولوم زیاد M1 (حجم ۳۰۰ > ۶۴) با [2012.70 , 2013.20]
  ۱۴:۱۴ کلوز 2013.40 > سقف HV ⇒ مسلح شدن:
        سطح سفارش = 2013.20 + ۱ تیک = 2013.21
        حد ضرر     = 2012.70 − ۲ تیک = 2012.68
        R = HH(2022.00) − کف تأیید میانی(2012.00) = 10.00
        TP1 = 2012.00 + 0.382×10 = 2015.82 · TP2 = 2012.00 + 0.5×10 = 2017.00 · TPX = 2012.00 + 1.272×10 = 2024.72
  ۱۴:۱۶ پرشدن سفارش روی 2013.21
  ۱۴:۴۰ لمس TP1 (۳۳٪) و انتقال حد ضرر به ورود
  ۱۴:۵۵ لمس TP2 (۳۳٪)
  ۱۵:۲۰ لمس TPX (۳۴٪) ⇒ پایان معامله
"""
import math
import os

MS = 1000
DAY = 86_400_000
# دوشنبه ۱۹ اکتبر ۲۰۲۶ ۰۰:۰۰ UTC
MONDAY_2026_10_19 = 1792368000  # epoch seconds


def ts(hh, mm=0, day_offset=0):
    """مهر زمانی میلی‌ثانیه‌ای برای ساعت UTC داده‌شده در دوشنبهٔ سناریو."""
    return (MONDAY_2026_10_19 + day_offset * 86400 + hh * 3600 + mm * 60) * MS


def r6(x):
    return round(x, 6)


class Builder:
    def __init__(self):
        self.bars = []          # (t, o, h, l, c, v)

    def add(self, t, o, h, l, c, v):
        self.bars.append((int(t), r6(o), r6(h), r6(l), r6(c), r6(v)))

    # ── یک ساعت با پروفایل حجم «ردیفی» (هر کندل M1 داخل یک ردیف) ──────────
    def hour_profile(self, hour, o, c, l, h, row_vols):
        """
        ۶۰ کندل M1 می‌سازد که هر کدام کاملاً داخل یکی از ۲۴ ردیف پروفایل می‌نشیند؛
        پس حجم هر ردیف دقیقاً برابر مجموع حجم کندل‌های همان ردیف است.
        row_vols = لیست ۲۴تایی (اگر None ⇒ پروفایل نزولیِ اکید ⇒ هیچ ناحیه‌ای ساخته نمی‌شود).
        """
        step = (h - l) / 24.0
        if row_vols is None:
            row_vols = [300 - 9 * r for r in range(24)]      # اکیداً نزولی از کف به سقف
        assert len(row_vols) == 24
        counts = [3 if r < 12 else 2 for r in range(24)]      # 12*3 + 12*2 = 60
        by_row = {}
        for r in range(24):
            rb = l + r * step
            lo_c = l if r == 0 else rb + 0.02
            hi_c = h if r == 23 else rb + step - 0.02
            n = counts[r]
            vol_each = row_vols[r] / n
            candles = []
            for i in range(n):
                v = vol_each if i < n - 1 else row_vols[r] - vol_each * (n - 1)
                o_c = lo_c + 0.25 * (hi_c - lo_c) + i * 0.001
                c_c = hi_c - 0.25 * (hi_c - lo_c) + i * 0.001
                candles.append([o_c, hi_c, lo_c, c_c, v])
            by_row[r] = candles
        start_row = min(23, max(0, int((o - l) / step)))
        close_row = min(23, max(0, int((c - l) / step)))
        order = list(range(start_row, -1, -1)) + list(range(start_row + 1, 24))
        order = [r for r in order if r != close_row] + [close_row]
        seq = []
        for r in order:
            seq.extend([(r, cd) for cd in by_row[r]])
        assert len(seq) == 60, len(seq)
        # اولین open و آخرین close را به مقادیر طراحی‌شده می‌چسبانیم
        seq[0][1][0] = o
        seq[0][1][1] = max(seq[0][1][1], o + 0.005)
        seq[0][1][2] = min(seq[0][1][2], o - 0.005)
        seq[-1][1][3] = c
        seq[-1][1][1] = max(seq[-1][1][1], c + 0.005)
        seq[-1][1][2] = min(seq[-1][1][2], c - 0.005)
        for i, (r, cd) in enumerate(seq):
            self.add(ts(hour) + i * 60 * MS, cd[0], cd[1], cd[2], cd[3], cd[4])

    # ── یک ساعت با مسیر دقیق «دقیقه‌به‌دقیقه» ──────────────────────────────
    def hour_explicit(self, hour, minutes):
        """minutes = لیست دقیقه‌به‌دقیقه (o,h,l,c,v) — می‌تواند کمتر از ۶۰ باشد (ساعت ناتمام)"""
        assert len(minutes) <= 60
        for i, m in enumerate(minutes):
            self.add(ts(hour) + i * 60 * MS, m[0], m[1], m[2], m[3], m[4])


def flat_vol(n, v):
    return [v] * n


def build():
    b = Builder()

    # ── ۰۲..۱۲ : ساعت‌های ساختاری با پروفایل ردیفی ─────────────────────────
    # 02:00 نزولی
    b.hour_profile(2, o=2010.00, c=2005.05, l=2004.00, h=2010.50, row_vols=None)
    # 03:00 صعودی (کندل مهم پایین‌ترین‌ها: low=1999.00)
    b.hour_profile(3, o=2005.05, c=2007.50, l=1999.00, h=2008.00, row_vols=None)
    # 04:00 صعودی (Ready BU چون کلوز 2009.50 > high کندل مهم 2008.00)
    b.hour_profile(4, o=2007.50, c=2009.50, l=2006.50, h=2010.00, row_vols=None)
    # 05:00 نزولی (کندل مهم بالاترین‌ها: high=2010.20)
    b.hour_profile(5, o=2009.50, c=2007.00, l=2005.50, h=2010.20, row_vols=None)
    # 06:00 نزولی (Ready BE چون کلوز 2004.00 < low کندل مهم 2005.50) ⇒ tempbox [1999.00 , 2010.20]
    b.hour_profile(6, o=2007.00, c=2004.05, l=2003.00, h=2007.20, row_vols=None)
    # 07:00 صعودی (کلوز 2012.10 > سقف tempbox 2010.20 ⇒ روند صعودی)
    b.hour_profile(7, o=2004.05, c=2012.10, l=2003.50, h=2012.50, row_vols=None)

    # 08:00 صعودی ⇒ ناحیهٔ ساختار Z1
    zone_rows = [5, 8, 12, 16, 50, 50, 50, 40, 32, 25, 20, 20,
                 25, 31, 38, 46, 55, 65, 76, 88, 100, 115, 130, 145]
    b.hour_profile(8, o=2012.10, c=2015.30, l=2011.00, h=2015.80, row_vols=zone_rows)

    # 09:00 صعودی (بدون ناحیه)
    b.hour_profile(9, o=2015.30, c=2019.00, l=2014.50, h=2019.50, row_vols=None)
    # 10:00 نزولی با high=2022.00 ⇒ کندل مهم بالاترین‌ها
    b.hour_profile(10, o=2019.00, c=2017.00, l=2016.00, h=2022.00, row_vols=None)
    # 11:00 نزولی ⇒ کلوز 2015.00 < low کندل مهم 2016.00 ⇒ Ready BE ⇒ pinBE=2022.00 (HH)
    b.hour_profile(11, o=2017.00, c=2015.00, l=2014.00, h=2017.50, row_vols=None)
    # 12:00 نزولی
    b.hour_profile(12, o=2015.00, c=2013.60, l=2013.30, h=2015.20, row_vols=None)

    # ── ۱۳:۰۰ : ساعت برخورد با ناحیهٔ ساختار و تأیید میانی ──────────────────
    m13 = []
    # 13:00..13:19 آرام نزولی 2013.60 → 2013.10
    for i in range(20):
        p = 2013.60 - (0.50 * i / 19.0)
        m13.append((p + 0.02, p + 0.05, p - 0.05, p, 100))
    # 13:20..13:21
    m13.append((2013.10, 2013.12, 2013.02, 2013.05, 100))
    m13.append((2013.05, 2013.08, 2013.00, 2013.02, 100))
    # 13:22 کندل برخورد: low=2012.00 (کف تأیید میانی) — کلوز 2012.30 بالای کف ناحیه 2012.20
    m13.append((2013.00, 2013.05, 2012.00, 2012.30, 100))
    # 13:23..13:29 بازگشت آرام به بالای ناحیه
    for i in range(7):
        p = 2012.40 + (0.60 * i / 6.0)
        m13.append((p, p + 0.06, p - 0.06, p + 0.03, 100))
    # 13:30..13:49 آرام صعودی 2013.00 → 2013.10
    for i in range(20):
        p = 2013.00 + (0.10 * i / 19.0)
        m13.append((p, p + 0.05, p - 0.05, p, 100))
    # 13:50..13:54 کندل ولوم کم M5: حجم ۸۰/دقیقه = ۴۰۰ (کمتر از ۵۰۰ قبلی) ؛ [2012.60 , 2013.15]
    lv = [(2013.10, 2013.12, 2013.00, 2013.05, 80),
          (2013.05, 2013.10, 2012.90, 2012.95, 80),
          (2012.95, 2013.00, 2012.60, 2012.70, 80),
          (2012.70, 2013.05, 2012.65, 2013.00, 80),
          (2013.00, 2013.15, 2012.95, 2013.10, 80)]
    m13.extend(lv)
    # 13:55..13:59 حجم ۶۴ (بدون افزایش) — کلوز زیر سقف LV ⇒ هنوز تأیید نشده
    for i in range(5):
        p = 2013.10 - 0.01 * i
        m13.append((p, p + 0.03, p - 0.03, p - 0.01, 64))
    b.hour_explicit(13, m13)

    # ── ۱۴:۰۰ : تأیید LV ، بازگشت به باکس ، کندل ولوم زیاد ، مسلح‌شدن ، ورود ──
    m14 = []
    # 14:00..14:04 صعود تا کلوز 2013.40 > سقف LV (2013.15) ⇒ تأیید LV
    for i in range(5):
        p = 2013.09 + (0.31 * i / 4.0)
        m14.append((p, p + 0.04, p - 0.03, p, 64))
    # 14:05..14:10 بازگشت به داخل باکس LV (کف 2012.90 بالای کف باکس 2012.60)
    probe_v = float(__import__('os').environ.get('PROBE_1405_VOL', '64'))
    m14.append((2013.40, 2013.42, 2013.20, 2013.25, probe_v))
    m14.append((2013.25, 2013.28, 2012.90, 2013.00, 64))
    m14.append((2013.00, 2013.10, 2012.95, 2013.05, 64))
    m14.append((2013.05, 2013.12, 2012.98, 2013.08, 64))
    m14.append((2013.08, 2013.14, 2013.00, 2013.10, 64))
    m14.append((2013.10, 2013.16, 2013.02, 2013.12, 64))
    # 14:11 کندل ولوم زیاد: حجم ۳۰۰ > ۶۴ ⇒ [2012.70 , 2013.20]
    m14.append((2013.12, 2013.20, 2012.70, 2013.10, 300))
    # 14:12..14:13
    m14.append((2013.10, 2013.15, 2013.00, 2013.08, 64))
    m14.append((2013.08, 2013.18, 2013.02, 2013.15, 64))
    # 14:14 کلوز 2013.40 > سقف HV 2013.20 ⇒ مسلح (سطح سفارش 2013.21)
    m14.append((2013.15, 2013.42, 2013.10, 2013.40, 64))
    # 14:15 کندل مسلح‌شدن + 1 (پر شدن در همان کندل مسلح‌شدن مجاز نیست)
    m14.append((2013.40, 2013.45, 2013.30, 2013.35, 64))
    # 14:16 پرشدن سفارش روی 2013.21 (low = 2013.10)
    m14.append((2013.35, 2013.38, 2013.10, 2013.30, 64))
    # 14:17..14:39 صعود آرام تا زیر TP1 (2015.82)
    for i in range(23):
        p = 2013.30 + (2.20 * i / 22.0)
        m14.append((p, p + 0.05, p - 0.05, p, 64))
    # 14:40 لمس TP1 : high = 2015.90
    m14.append((2015.50, 2015.90, 2015.40, 2015.75, 64))
    # 14:41..14:54 ادامهٔ صعود تا زیر TP2 (2017.00)
    for i in range(14):
        p = 2015.75 + (1.10 * i / 13.0)
        m14.append((p, p + 0.05, p - 0.05, p, 64))
    # 14:55 لمس TP2 : high = 2017.10
    m14.append((2016.85, 2017.10, 2016.75, 2017.00, 64))
    # 14:56..14:59
    for i in range(4):
        p = 2017.00 + 0.05 * i
        m14.append((p, p + 0.05, p - 0.05, p, 64))
    b.hour_explicit(14, m14)

    # ── ۱۵:۰۰ تا ۱۵:۳۰ : صعود تا TPX = 2024.72 (ساعت ساختار بسته نمی‌شود) ──
    m15 = []
    for i in range(20):
        p = 2017.15 + (2024.60 - 2017.15) * i / 19.0
        m15.append((p, p + 0.06, p - 0.06, p, 64))
    # دقیقهٔ ۱۵:۲۰ : لمس TPX
    m15.append((2024.60, 2024.80, 2024.55, 2024.75, 64))
    for i in range(9):
        p = 2024.75 - 0.03 * i
        m15.append((p, p + 0.05, p - 0.05, p, 64))
    b.hour_explicit(15, m15[:30])

    return b.bars


def main():
    bars = build()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.environ.get("OUT_CSV", "m1.csv"))
    with open(out, "w", encoding="utf-8") as f:
        f.write("time,open,high,low,close,volume\n")
        for (t, o, h, l, c, v) in bars:
            f.write(f"{t},{o:.6f},{h:.6f},{l:.6f},{c:.6f},{v:.6f}\n")
    print(f"نوشته شد: {out}  ({len(bars)} کندل M1)")

    # خلاصهٔ تجمیع H1 برای بازبینی چشمی
    def agg(n_min):
        res = []
        for i in range(0, len(bars), n_min):
            chunk = bars[i:i + n_min]
            if len(chunk) < n_min:
                break
            o = chunk[0][1]; c = chunk[-1][4]
            h = max(x[2] for x in chunk); l = min(x[3] for x in chunk)
            v = sum(x[5] for x in chunk)
            res.append((chunk[0][0], o, h, l, c, v))
        return res

    for (t, o, h, l, c, v) in agg(60):
        hh = (t // MS % 86400) // 3600
        kind = "صعودی" if c > o else ("نزولی" if c < o else "دوجی")
        print(f"H1 {hh:02d}:00  o={o:9.2f} h={h:9.2f} l={l:9.2f} c={c:9.2f}  {kind}  vol={v:8.0f}")


if __name__ == "__main__":
    main()
